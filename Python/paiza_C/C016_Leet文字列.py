"""
Leet と呼ばれるインターネットスラングがあります。
Leet ではいくつかのアルファベットをよく似た形の他の文字に置き換えて表記します。

Leet の置き換え規則はたくさんありますが、ここでは次の置き換え規則のみを考えましょう。
"""
# 文字列を定義する
words = list(input())


# 変換表を作成する
word_dict = {
    "A": "4",
    "E": "3",
    "G": "6",
    "I": "1",
    "O": "0",
    "S": "5",
    "Z": "2"
}


# 出力用のデータを作成する
output = []
for w in words:
    # get(辞書にある, ない)で追加できる。変数は同じだが、意味は違う。
    output.append(word_dict.get(w, w))
    
    
# 半角スペースなしで出力する    
print("".join(output))


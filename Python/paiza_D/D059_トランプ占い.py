"""
著名な占い師であるあなたはとある国の大統領から占いを依頼されました。
正しい占いをしたいところですが、この大統領は気難しいのであまり悪い結果を伝えるのはためらわれます。

占いの結果はトランプカード "J", "Q", "K" の 2 枚 1 組で表れます。
もし結果が「最悪」を表す "J" 2 枚になってしまったときには片方 (2 枚目) を "Q" に変更するプログラムを作ってください。
"""

cards = input().split()

if(cards[0] == "J" and cards[1] == "J"):
    cards[1] = "Q"

print(*cards)
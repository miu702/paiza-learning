"""
あなたは A のボタン、 B のボタンの 2 つのボタンを使うゲームを作っています。
このゲームではキャラクターを動かして遊びます。
キャラクターははじめ座標 0 の位置にいて、A のボタンを押すとキャラクターが 1 マス右に進み (座標が 1 増える)、
B のボタンを押すとキャラクターが 1 マス左に進み (座標が 1 減る) ます。

A, B のボタンそれぞれ何回押したが入力されるので、
ボタンが全て押された後のキャラクターの位置の座標を出力するプログラムを作成してください。
"""

numbers = input().split()
A = int(numbers[0])
B = int(numbers[1])

step = A - B
print(step)
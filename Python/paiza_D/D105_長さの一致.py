"""
あなたは2つの文字列の長さを目で比較していましたが
長い文字では目視で確認するのが辛くなってきました。

2つの文字列が入力されるので文字列の長さが一致していれば 
"Yes" 、違う場合は "No" と出力するプログラムを作成してください。
"""

# 変数をlistにすることで、len()で長さを比較する
word1 = list(input())
word2 = list(input())


# 2つの要素を比較し、一致しているときのみ、Yes
if len(word1) == len(word2):
    print("Yes")
else:
    print("No")

"""
あなたは薬の製造をしています。
薬の効き目を 24 時間持続させるためにどれくらいの薬が必要なのか計算するために
プログラムを作成することにしました。

1 錠あたりの薬の効き目 t 時間が与えられます。
24 時間以上効果を持続させるためには最低何錠の薬を飲む必要があるかを出力して下さい。
"""

# 効き目の時間で割った時に余りが0でない時は、+1することで求めることができる
efficacy = int(input())

days = 24
need = days // efficacy
rest = days % efficacy


print(need if rest == 0 else need + 1)
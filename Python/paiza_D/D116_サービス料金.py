"""
あるお店では、お会計の金額の下二桁、100 円未満の部分を割引サービスしています。
例えば 1,080 円の場合、80 円割引されます。

割引前のお会計の金額が与えられるので、割引後の金額を出力してください。
"""
price = input()

# 入力値をコピーして、処理用変数を作成する
copy_price = price[::1]

# 今回は100円単位にするので、下2桁をカットする
processing = copy_price[:len(copy_price) - 2]


#　カットした要素と00をくっつける
under = "00"
print(processing + under)
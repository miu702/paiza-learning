"""
1 から 15 までの整数 N が入力されるので、円周率を小数点第 N 位まで出力してください。
例えば N = 2 の場合、答えは 3.14 となります。

また、円周率の小数点第 15 位までは 3.141592653589793 です。
"""

# 桁数を標準入力から取得する
digit = int(input())

# 円周率を15桁まで記述。また、円周率は数値だが、処理では範囲を指定するので、文字列型で定義。
pi = "3.141592653589793"

# コピーして、範囲を指定して出力する
pi_processing = pi[::1]
output = pi_processing[:digit + 2]
print(output)
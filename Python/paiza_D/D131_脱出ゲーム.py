"""
あなたは、脱出ゲームをしていて、部屋の鍵のところに "012" なるメモがあるのを見つけました。

これまでのゲーム結果から、このような暗号は数字が文字の穴の数に対応していて、
かつ構成する文字は A, B, C のみであることがわかっています。


文字の穴の数は A が 1 個、B が 2 個、C が 0 個であるので、
"012" は "CAB" を表すことがわかります。
このような暗号が与えられるので、復号した文字列を出力してください。
"""

# 暗号を記述
cipher = list(input())


# 辞書を作成する
dist = {
    "0": "C",
    "1": "A",
    "2": "B",
}

# 文字を複合する
answer = []
for c in cipher:
    answer.append(dist.get(c))
    
    
# 配列を結合する
print("".join(answer))


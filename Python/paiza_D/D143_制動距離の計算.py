"""
あなたはある車を購入しました。あらかじめ入念に自動車の特性を把握しておきたいあなたは、
ある速度で進行している時にブレーキをかけてから停止するまでに何メートル進むか調べることにしました。
この距離を制動距離と言います。
制動距離は、摩擦がない場合を考えると車の重さを m, ブレーキをかけ始めたときの速度を v, 
ブレーキの強さを f としたとき、以下のように表せます。

L = MVV / 2F
以上の値が与えられるので、制動距離 L を求めるプログラムを作成してください。
ただし、小数点以下は切り捨てて出力してください。
"""

# 入力 → 変数に変換する。
import sys
numbers = list(map(int, sys.stdin.read().split()))
M = numbers[0]
V = numbers[1]
F = numbers[2]

# 計算を実施する
brakingDistance = (M * V * V) / (2 * F)
print(int(brakingDistance))


"""
あなたは今だるま落としで遊んでいます。
そのだるま落としは 5 段の木片からなり、その木片には 1 つにつき 1 つの英字小文字が書いてあります。


木片を飛ばす前の文字列と、飛ばしたのが何段目の木片であったかが与えられるので、
木片を飛ばした後の文字列を求めるプログラムを作成してください。
"""

# 配列と数値を定義する
words = list(input())
number = int(input())

# インデックス番号の位置になったら、配列に追加しないことで疑似的にだるま落としを実装する
output = []
for i in range(len(words)):
    if i != number - 1:
        output.append(words[i])

print("".join(output))



"""
日本では日付を 2020年10月31日 と言ったように年、月、日の順に記載します。
一方アメリカなどでは 月、日、年の順で 10/31/2020 などと記載します。

日本で一般的な順の年、月、日の順に日付が改行区切りで与えられるので
アメリカなどで使われている形式で月/日/年の形式で出力してください。
"""

# 入力 → 変数に変換する。
year = int(input())
month = int(input())
day = int(input())


# 日付を作成する
full_date = f"{month}/{day}/{year}"
print(full_date)
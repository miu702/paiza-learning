"""
あなたは買い物をしたときにポイントが付く通販サイトを作成しています。

1000 円以上の買い物をしたときに購入金額の 10 %のポイントが付与されます。
1000 円未満の場合はポイントは 0 となります。
また小数点以下のポイントは切り捨てられます。

購入金額 n 円が入力されるので何ポイント付与されるかを出力してください。
"""

# 入力 → 変数に変換する。
price = int(input())


# ポイントを計算する。10%なので、10で割って商の分だけポイントとする
limit = 1000
if(price >= limit):
    points = price // 10
    print(points)
else:
    print(0)


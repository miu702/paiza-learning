"""
あなたはカードを使ったゲームをする準備をしています。
このゲームでは n 枚のカードを m 人に p 枚ずつカードを配りゲームを始めます。

カードの枚数 n 枚、ゲームに参加する人数 m 人、1人に配るカードの枚数 p 枚が改行区切りで与えられるので、
カードを配ったあとに残るカードの枚数を出力してください。
"""

# 全体のカードの数、1人の手札、プレイヤー数を定義
card = int(input())
hand = int(input())
players = int(input())


# 残りのページを計算し、出力する
rest = card - (hand * players)
print(rest)
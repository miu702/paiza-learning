"""
あなたはある呪文の文字列を解読するためにプログラムを作成しています。
文字列の奇数番目を取り出して順に並べると解読できることがわかったあなたは解読プログラムを書くことにしました。

文字列 S が与えられるので奇数文字目を取り出し、取り出した順に並べ 1 行で出力してください。
"""


# 呪文を定義する
magic = list(input())


# 今回は奇数番目を取り出すので、インデックス番号で偶数の要素を配列に投入する
output = []
for m in range(len(magic)):
    if m % 2 == 0:
        output.append(magic[m])

# 配列の要素をスペースなしで出力する
print("".join(output))


"""
あなたはスーパーに買い物をしに来ました。
あなたは様々な商品をカートにいれ、その合計金額は X 円でした。

スーパーのポイントカードには P ポイント貯まっており、1 ポイント 1 円から利用することができます。
あなたはポイントをできる限り使ってお会計をすることにしました。

あなたが支払う金額を出力してください。
支払う金額がマイナスになる場合はなく最大でも 0 円までという点に注意してください。
"""

# 入力 → 変数に変換する。
import sys
numbers = list(map(int, sys.stdin.read().split()))

# 価格と所持ポイントを定義する
price = numbers[0]
points = numbers[1]

# 価格と所持ポイントを比べ、ポイントの方が多いなら、無料(0)を出力し、価格が多いなら、ポイントを全て使う。
print(0 if price <= points else price - points)


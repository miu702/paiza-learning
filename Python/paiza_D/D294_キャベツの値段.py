"""
あなたはキャベツを購入しようとしています。
キャベツは 1 玉と 1/2 玉で販売されています。

どちらで買うか迷ったあなたはひとまず 1 玉あたりにするといくら高いのかを求めることにしました。

キャベツ 1 玉の値段 n とキャベツ 1/2 玉の値段 m が改行区切りで与えられるので 1/2 玉を 1 玉分買った場合に 
1 玉の値段 m に対していくら高いかを出力してください。
"""

# 1球の値段と半分の値段を定義する
full = int(input())
half = int(input())

# 半分を2つ勝った時の値段を計算し、いくら高いか出力する。(今回は半分×2の方が高いので、これでOK。)
half_d = half * 2
sub = half_d - full
print(sub)
"""
あなたはクリスマスパーティのためにケーキを用意することになりました。
ケーキはホール単位で買い 1 ホールを 6 等分することにします。

パーティに参加する人数 n が与えられるので全員にケーキが行き渡るには
何ホールのケーキを購入する必要があるか出力してください。
"""

# 人数を定義する
member = int(input())

# ケーキの量と余りを計算する
piece = 6
cake = member // piece
rest = member % piece


# 人が余っている時、1つケーキを追加する
print(cake + 1 if rest > 0 else cake)